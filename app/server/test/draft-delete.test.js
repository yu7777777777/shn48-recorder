"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("fs");
const os = require("os");
const path = require("path");
const http = require("http");
const root = fs.mkdtempSync(path.join(os.tmpdir(), "shn48-draft-delete-"));
process.env.DATA_DIR = root;
process.env.COVERS_DIR = path.join(root, "covers");
process.env.COOKIES_PATH = path.join(root, "cookies.json");
process.env.ADMIN_USERNAME = "test";
process.env.ADMIN_PASSWORD = "test-password";
process.env.SESSION_SECRET = "test-secret-at-least-sixteen";
const draft = require("../modules/bilibili/draft");
const manager = require("../modules/recorder/manager");
const { createApp } = require("../index");
test.after(() => fs.rmSync(root, { recursive: true, force: true }));
test("draft deletion validates confirmation, identity, upstream success, deduplication and preserves recordings", async () => {
  let deletes = [];
  let responseCode = 0;
  let invalidJson = false;
  const upstream = http.createServer(async (req, res) => {
    res.setHeader("Content-Type", "application/json");
    if (req.url.startsWith("/list")) return res.end(JSON.stringify({ code: 0, data: [{ id: 3834082, title: "同名草稿" }, { id: 3833795, title: "同名草稿" }] }));
    let body = "";
    for await (const chunk of req) body += chunk;
    deletes.push({ method: req.method, cookie: req.headers.cookie, type: req.headers["content-type"], body: new URLSearchParams(body) });
    await new Promise((resolve) => setTimeout(resolve, 30));
    res.end(invalidJson ? "not-json" : JSON.stringify({ code: responseCode }));
  });
  await new Promise((resolve) => upstream.listen(0, "127.0.0.1", resolve));
  process.env.BILI_DRAFT_LIST_URL = `http://127.0.0.1:${upstream.address().port}/list`;
  process.env.BILI_DRAFT_DELETE_URL = `http://127.0.0.1:${upstream.address().port}/delete`;
  fs.writeFileSync(process.env.COOKIES_PATH, JSON.stringify({ SESSDATA: "test-session", bili_jct: "test-csrf", DedeUserID: "1" }));
  const file = path.join(root, "preserved.mp4");
  fs.writeFileSync(file, "preserve-original");
  manager.addRecording({ id: "local-recording", title: "同名草稿", status: "done", uploadStatus: "done", filePath: file });
  manager.enqueueUpload({ recordingId: "local-recording", status: "done", title: "同名草稿" });
  const beforeRecords = JSON.stringify(manager.getRecordings());
  const beforeQueue = JSON.stringify(manager.getQueue());
  const server = createApp().listen(0, "127.0.0.1");
  await new Promise((resolve) => server.once("listening", resolve));
  const base = `http://127.0.0.1:${server.address().port}/api/admin`;
  try {
    const anonymous = await fetch(`${base}/bilibili/draft/3834082`, { method: "DELETE" });
    assert.equal(anonymous.status, 401);
    const login = await fetch(`${base}/auth/login`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ username: "test", password: "test-password" }) });
    assert.equal(login.status, 200);
    const cookie = login.headers.get("set-cookie").split(";")[0];
    const remove = (id, confirmed = true) => fetch(`${base}/bilibili/draft/${id}`, { method: "DELETE", headers: { Cookie: cookie, "Content-Type": "application/json" }, body: JSON.stringify({ confirmed }) });
    assert.equal((await remove("3834082", false)).status, 400);
    for (const id of ["0", "-1", "NaN", "1,2", "9007199254740993"]) assert.equal((await remove(id)).status, 400);
    assert.equal((await remove("9999999")).status, 404);
    assert.equal(deletes.length, 0);
    const responses = await Promise.all([remove("3834082"), remove("3834082")]);
    assert.deepEqual(responses.map((r) => r.status).sort(), [200, 409]);
    assert.equal(deletes.length, 1);
    assert.equal(deletes[0].body.get("id"), "3834082");
    assert.equal(deletes[0].body.get("csrf"), "test-csrf");
    assert.equal(deletes[0].body.get("csrf_token"), "test-csrf");
    assert.equal(deletes[0].method, "POST");
    assert.equal(deletes[0].type, "application/x-www-form-urlencoded");
    responseCode = -101;
    assert.equal((await remove("3833795")).status, 502);
    responseCode = 0;
    invalidJson = true;
    assert.equal((await remove("3833795")).status, 502);
    const count = deletes.length;
    await assert.rejects(draft.deleteDraft({ draftId: "3834082", cookie: "test", csrf: "" }), /凭据/);
    assert.equal(deletes.length, count);
    assert.equal(JSON.stringify(manager.getRecordings()), beforeRecords);
    assert.equal(JSON.stringify(manager.getQueue()), beforeQueue);
    assert.equal(fs.readFileSync(file, "utf8"), "preserve-original");
  } finally {
    server.closeAllConnections(); upstream.closeAllConnections();
    await Promise.all([new Promise((resolve) => server.close(resolve)), new Promise((resolve) => upstream.close(resolve))]);
  }
});
