"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("fs");
const os = require("os");
const path = require("path");
const { spawnSync } = require("child_process");
const root = fs.mkdtempSync(path.join(os.tmpdir(), "shn48-clips-"));
process.env.DATA_DIR = path.join(root, "data");
process.env.RECORDINGS_DIR = path.join(root, "recordings");
fs.mkdirSync(process.env.RECORDINGS_DIR);
const manager = require("../modules/recorder/manager");
const clips = require("../modules/recorder/clips");
const archive = require("../modules/recorder/archive-processor");
const storage = require("../modules/recorder/storage");
const express = require("express");
let server;
test.after(async () => { clips.stop(); if (server) { server.closeAllConnections(); await new Promise(r => server.close(r)); } fs.rmSync(root, { recursive: true, force: true }); });
const ffmpeg = process.env.FFMPEG_BIN || "ffmpeg";
const available = !spawnSync(ffmpeg, ["-version"]).error && !spawnSync(process.env.FFPROBE_BIN || "ffprobe", ["-version"]).error;
async function settled(id) {
  const deadline = Date.now() + 30000;
  while (["clip_queued", "clip_processing"].includes(manager.getRecording(id).status)) {
    if (Date.now() > deadline) throw new Error("clip timeout");
    await new Promise(r => setTimeout(r, 30));
  }
  return manager.getRecording(id);
}
test("rejects malformed ranges, unavailable parents and files outside recording root", () => {
  for (const values of [[-1, 2], [0, 0], [3, 2], [0, Infinity], ["0", 2], [null, 3], [0, 7201]]) assert.throws(() => clips._internals.range(...values));
  assert.throws(() => clips._internals.range(0, 5, 4));
  const pending = manager.addRecording({ status: "recording" });
  assert.throws(() => clips.enqueue(pending.id, { start: 0, end: 2 }), /归档/);
  manager.updateRecording(pending.id, { status: "failed" });
  const file = path.join(root, "outside.mp4"); fs.writeFileSync(file, "keep");
  const outside = manager.addRecording({ status: "done", filePath: file });
  assert.throws(() => clips.enqueue(outside.id, { start: 0, end: 2 }), /outside/);
});
test("real clipping preserves source, locks deletion, exports exact range, and keeps title for draft upload", { skip: !available }, async () => {
  const source = path.join(process.env.RECORDINGS_DIR, "source.mp4");
  const generated = spawnSync(ffmpeg, ["-v", "error", "-y", "-f", "lavfi", "-i", "testsrc2=size=160x120:rate=25", "-f", "lavfi", "-i", "sine=frequency=440", "-t", "5", "-c:v", "libx264", "-threads", "1", "-c:a", "aac", source]);
  assert.equal(generated.status, 0, generated.stderr?.toString());
  const sourceBytes = fs.readFileSync(source);
  const parent = manager.addRecording({ title: "原片", memberName: "成员", status: "done", filePath: source });
  const recording = manager.addRecording({ status: "recording" });
  const clip = clips.enqueue(parent.id, { start: 1.24, end: 3.56, title: "自定义片段标题" });
  assert.equal(clips.enqueue(parent.id, { start: 1.24, end: 3.56 }).id, clip.id);
  await clips._internals.pump();
  assert.equal(clip.status, "clip_queued");
  assert.equal(storage.locked(parent), true);
  const app = express(); app.use(express.json()); app.use("/recordings", require("../routes/recordings"));
  server = app.listen(0, "127.0.0.1"); await new Promise(r => server.once("listening", r));
  const base = `http://127.0.0.1:${server.address().port}/recordings`;
  assert.equal((await fetch(`${base}/${parent.id}`, { method: "DELETE" })).status, 409);
  assert.equal((await fetch(`${base}/${clip.id}`, { method: "DELETE" })).status, 409);
  manager.updateRecording(recording.id, { status: "failed" });
  await clips._internals.pump();
  await settled(clip.id);
  assert.equal(clip.status, "done", clip.clipError);
  assert.ok(Math.abs(clip.duration - 2.32) < 0.15);
  assert.deepEqual(fs.readFileSync(source), sourceBytes);
  assert.equal(storage.locked(parent), false);
  assert.equal((await archive.prepareForUpload(clip.id)).title, "自定义片段标题");
  const queueItem = require("../modules/bilibili/queue")._internals.buildItem(clip, { mode: "draft" });
  assert.equal(queueItem.title, "自定义片段标题"); assert.equal(queueItem.file, clip.filePath);
  const response = await fetch(`${base}/${clip.id}/file`, { headers: { Range: "bytes=0-99" } });
  assert.equal(response.status, 206); assert.equal((await response.arrayBuffer()).byteLength, 100);
  const bad = clips.enqueue(parent.id, { start: 4, end: 10 }); await settled(bad.id);
  assert.equal(bad.status, "clip_failed"); assert.match(bad.clipError, /时长/);
  assert.equal(bad.filePath, null);
  manager.updateRecording(bad.id, { clipEnd: 5, duration: 1, segments: [{ start: 4, end: 5 }] }); clips.retry(bad.id); await settled(bad.id);
  assert.equal(bad.status, "done", bad.clipError);
  const joined = clips.enqueue(parent.id, { segments: [{ start: 3, end: 4.5 }, { start: 0, end: 1.5 }], title: "多段拼接" });
  await settled(joined.id);
  assert.equal(joined.status, "done", joined.clipError);
  assert.ok(Math.abs(joined.duration - 3) < .15);
  assert.deepEqual(joined.segments, [{ start: 0, end: 1.5 }, { start: 3, end: 4.5 }]);
  assert.throws(() => clips.enqueue(parent.id, { segments: [{ start: 0, end: 2 }, { start: 1, end: 3 }] }), /重叠/);
  assert.throws(() => clips.enqueue(parent.id, { segments: [] }), /30/);
  assert.throws(() => clips.enqueue(parent.id, { segments: Array(31).fill({ start: 0, end: 1 }) }), /30/);
  assert.equal((await fetch(`${base}/${parent.id}`, { method: "DELETE" })).status, 200);
  assert.ok(fs.existsSync(clip.filePath));
});
test("silent multisegment output preserves selected scene order and drops the middle", { skip: !available }, async () => {
  const file = path.join(process.env.RECORDINGS_DIR, "colors.mp4");
  const result = spawnSync(ffmpeg, ["-v", "error", "-y", "-f", "lavfi", "-i", "color=red:s=160x120:r=25:d=2", "-f", "lavfi", "-i", "color=green:s=160x120:r=25:d=2", "-f", "lavfi", "-i", "color=blue:s=160x120:r=25:d=2", "-filter_complex", "[0:v][1:v][2:v]concat=n=3:v=1:a=0[v]", "-map", "[v]", "-c:v", "libx264", "-threads", "1", file]);
  assert.equal(result.status, 0, result.stderr?.toString());
  const parent = manager.addRecording({ status: "done", filePath: file, title: "颜色顺序" });
  const item = clips.enqueue(parent.id, { segments: [{ start: .5, end: 1.5 }, { start: 4.5, end: 5.5 }] });
  await settled(item.id); assert.equal(item.status, "done", item.clipError);
  assert.ok(Math.abs(item.duration - 2) < .15);
  const pixel = second => {
    const frame = spawnSync(ffmpeg, ["-v", "error", "-ss", String(second), "-i", item.filePath, "-frames:v", "1", "-vf", "scale=1:1", "-pix_fmt", "rgb24", "-f", "rawvideo", "pipe:1"]);
    assert.equal(frame.status, 0); return [...frame.stdout];
  };
  const first = pixel(.4), last = pixel(1.4);
  assert.ok(first[0] > 200 && first[1] < 30 && first[2] < 30, `Expected red: ${first}`);
  assert.ok(last[2] > 200 && last[0] < 30 && last[1] < 30, `Expected blue: ${last}`);
});
