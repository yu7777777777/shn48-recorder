"use strict";
const router=require('express').Router(),service=require('../modules/pocket48/room-voice');
const wrap=fn=>async(req,res)=>{try{res.json({success:true,data:await fn(req)});}catch(e){res.status(e.statusCode||400).json({success:false,error:e.message});}};
router.get('/',wrap(()=>service.status()));
router.put('/watches',wrap(req=>service.saveWatch(req.body)));
router.delete('/watches/:id',wrap(req=>service.removeWatch(req.params.id)));
router.post('/record',wrap(req=>service.record(req.body)));
router.post('/:id/stop',wrap(req=>service.stop(req.params.id)));
router.get('/:id/messages',wrap(req=>service.messages(req.params.id)));
module.exports=router;
